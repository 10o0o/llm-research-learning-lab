SCOPE_PROMPT = """scope는 아래와 같은 규칙으로 작성하세요.

업무 포털 관련 문의는 "in_scope"를 할당하세요.
관련 없는 요청은 "out_of_scope"를 할당하세요.

범위 밖이면 summary에 서비스 범위 밖이라는 안내를 넣고, 추가 질문이나 요청 수행은 하지 마세요.

목록 항목에 적을 내용이 없으면 빈 배열로 작성하세요.
한국어로 작성하고, JSON 밖의 설명이나 코드 블록은 포함하지 마세요.

근거가 부족하더라도 업무 포털 관련 문의라면 "in_scope"를 할당하세요

문의 주제로 범위를 판단하고, 문서 유무는 답변 가능 여부에만 사용하세요."""

FACTS_PROMPT = """facts에는 문의 본문에서 확인되는 상황, 행동, 질문에 대해서만 구성하세요.
규정 내용을 facts로 구성하지 마세요."""


def build_prompt(documents, account_info=None):
    DOCUMENT_PROMPT = f"""아래 규정 문서는 처리 절차와 조직 정책의 근거입니다.
문서에 없는 절차, 조직 정책, 처리 기한을 일반 지식으로 추측하지 마세요.
별도로 제공된 계정 조회 결과는 현재 상태의 근거로 사용하세요.
조회된 상태가 규정 문서에 없다는 이유로 그 조회 결과까지 확인 불가로 처리하지 마세요.

아래는 제공된 규정 문서입니다.

{documents}
"""

    prompts = [
        SYSTEM_PROMPT,
        FORMAT_PROMPT,
        ANSWER_PROMPT,
        SOURCE_PROMPT,
        MISSING_INFORMATION_PROMPT,
        SCOPE_PROMPT,
        FACTS_PROMPT,
        DOCUMENT_PROMPT,
    ]

    if account_info is not None:
        ACCOUNT_PROMPT = f"""현재 요청자의 계정 상태는 아래와 같습니다.

id: {account_info["id"]}
status: {account_info["status"]}"""

        prompts.append(ACCOUNT_PROMPT)

    return "\n\n".join(prompts)
